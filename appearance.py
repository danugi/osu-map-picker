"""Persistent visual appearance, independent from search presets.

User images are stored as local WebP files next to the SQLite database
(``<data>/appearance``).  The browser receives the current image as a data
URI generated by :func:`background_data_uri`; a local filesystem path is never
placed into CSS.  Settings live in the ``preferences`` table under one key and
are therefore never embedded into search-preset JSON.
"""

from __future__ import annotations

import base64
import hashlib
import io
import json
import os
import re
from dataclasses import asdict, dataclass
from pathlib import Path

from PIL import Image, ImageOps, UnidentifiedImageError

MAX_UPLOAD_BYTES = 12 * 1024 * 1024
MAX_PIXELS = 40_000_000
MAX_STORED_SIDE = 2560
STORED_FORMAT = "WEBP"
STORED_SUFFIX = ".webp"
PREFERENCE_KEY = "appearance_v1"
SUPPORTED_FORMATS = frozenset({"PNG", "JPEG", "WEBP"})
THEMES = ("modern_glass", "osu_minimal", "dark_clean")
THEME_ALIASES = {
    "default": "modern_glass",
    "dark": "dark_clean",
    "custom": "modern_glass",
}
FIT_MODES = ("cover", "contain")
_HEX = re.compile(r"^#[0-9a-fA-F]{6}$")


class AppearanceError(ValueError):
    """Invalid image or appearance setting."""


@dataclass
class AppearanceSettings:
    theme: str = "modern_glass"
    background_file: str | None = None
    background_name: str = ""
    fit: str = "cover"
    position_x: int = 50
    position_y: int = 50
    dim: float = 0.42
    blur: int = 4
    opacity: float = 1.0
    panel_opacity: float = 0.84
    accent: str = "#ff66aa"

    def to_dict(self) -> dict[str, object]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: object) -> "AppearanceSettings":
        if not isinstance(data, dict):
            raise AppearanceError("Настройки оформления: ожидался объект.")
        defaults = cls()
        theme = str(data.get("theme", defaults.theme))
        theme = THEME_ALIASES.get(theme, theme)
        if theme not in THEMES:
            theme = defaults.theme
        fit = str(data.get("fit", defaults.fit))
        if fit not in FIT_MODES:
            fit = defaults.fit
        accent = str(data.get("accent", defaults.accent)).strip()
        if not _HEX.match(accent):
            accent = defaults.accent
        background_file = data.get("background_file")
        if not isinstance(background_file, str) or not background_file.strip():
            background_file = None
        else:
            background_file = Path(background_file).name
            if not background_file.endswith(STORED_SUFFIX):
                background_file = None
        background_name = data.get("background_name", "")
        if not isinstance(background_name, str):
            background_name = ""
        return cls(
            theme=theme,
            background_file=background_file,
            background_name=background_name[:160],
            fit=fit,
            position_x=_bounded_int(data.get("position_x"), 50, 0, 100),
            position_y=_bounded_int(data.get("position_y"), 50, 0, 100),
            dim=_bounded_float(data.get("dim"), defaults.dim, 0.0, 0.92),
            blur=_bounded_int(data.get("blur"), defaults.blur, 0, 30),
            opacity=_bounded_float(data.get("opacity"), defaults.opacity, 0.05, 1.0),
            panel_opacity=_bounded_float(
                data.get("panel_opacity"), defaults.panel_opacity, 0.35, 0.98
            ),
            accent=accent.lower(),
        )

    def validate(self) -> None:
        if self.theme not in THEMES:
            raise AppearanceError(f"Неизвестная тема: {self.theme!r}.")
        if self.fit not in FIT_MODES:
            raise AppearanceError(f"Неизвестный режим вписывания: {self.fit!r}.")
        if not _HEX.match(self.accent):
            raise AppearanceError("Акцент должен быть цветом вида #ff66aa.")
        for name, value, low, high in (
            ("position_x", self.position_x, 0, 100),
            ("position_y", self.position_y, 0, 100),
            ("blur", self.blur, 0, 30),
        ):
            if not isinstance(value, int) or not low <= value <= high:
                raise AppearanceError(f"{name}: ожидалось целое {low}..{high}.")
        for name, value, low, high in (
            ("dim", self.dim, 0.0, 0.92),
            ("opacity", self.opacity, 0.05, 1.0),
            ("panel_opacity", self.panel_opacity, 0.35, 0.98),
        ):
            if not isinstance(value, (int, float)) or not low <= float(value) <= high:
                raise AppearanceError(f"{name}: ожидалось число {low}..{high}.")
        if self.background_file:
            if (
                Path(self.background_file).name != self.background_file
                or not self.background_file.endswith(STORED_SUFFIX)
            ):
                raise AppearanceError("Недопустимое имя файла фона.")


@dataclass(frozen=True, slots=True)
class ProcessedImage:
    data: bytes
    width: int
    height: int
    source_format: str
    digest: str

    @property
    def mime_type(self) -> str:
        return "image/webp"


def appearance_dir(store: object) -> Path:
    """Directory beside the active database, never a temp upload folder."""

    database = Path(getattr(store, "path", Path("data/osu_picker.db")))
    path = database.parent / "appearance"
    path.mkdir(parents=True, exist_ok=True)
    return path


def default_appearance() -> AppearanceSettings:
    return AppearanceSettings()


def load_appearance(store: object) -> AppearanceSettings:
    raw = getattr(store, "get_preference")(PREFERENCE_KEY)
    if not raw:
        return default_appearance()
    try:
        return AppearanceSettings.from_dict(json.loads(raw))
    except (ValueError, TypeError, AppearanceError):
        return default_appearance()


def save_appearance(store: object, settings: AppearanceSettings) -> None:
    settings.validate()
    getattr(store, "set_preference")(
        PREFERENCE_KEY, json.dumps(settings.to_dict(), ensure_ascii=False)
    )


def process_image(raw: bytes) -> ProcessedImage:
    """Validate an upload and normalize it to a reasonably sized WebP."""

    if not raw:
        raise AppearanceError("Файл пуст.")
    if len(raw) > MAX_UPLOAD_BYTES:
        raise AppearanceError(
            f"Файл больше {MAX_UPLOAD_BYTES // (1024 * 1024)} МБ."
        )
    try:
        with Image.open(io.BytesIO(raw)) as probe:
            source_format = (probe.format or "").upper()
            if source_format not in SUPPORTED_FORMATS:
                raise AppearanceError(
                    "Поддерживаются только PNG, JPG/JPEG и WebP."
                )
            width, height = probe.size
            if width <= 0 or height <= 0:
                raise AppearanceError("У изображения некорректные размеры.")
            if width * height > MAX_PIXELS:
                raise AppearanceError("Слишком большое изображение по пикселям.")
            probe.verify()
    except AppearanceError:
        raise
    except (UnidentifiedImageError, OSError, ValueError) as exc:
        raise AppearanceError("Файл повреждён или не является изображением.") from exc

    try:
        with Image.open(io.BytesIO(raw)) as image:
            image = ImageOps.exif_transpose(image)
            if getattr(image, "is_animated", False):
                image.seek(0)
            if image.mode not in ("RGB", "RGBA"):
                image = image.convert("RGBA" if "A" in image.getbands() else "RGB")
            image.thumbnail((MAX_STORED_SIDE, MAX_STORED_SIDE), Image.Resampling.LANCZOS)
            output = io.BytesIO()
            image.save(
                output,
                format=STORED_FORMAT,
                quality=88,
                method=6,
                optimize=True,
            )
            data = output.getvalue()
            width, height = image.size
    except (UnidentifiedImageError, OSError, ValueError) as exc:
        raise AppearanceError("Не удалось обработать изображение.") from exc

    if not data:
        raise AppearanceError("Не удалось сохранить изображение.")
    return ProcessedImage(
        data=data,
        width=width,
        height=height,
        source_format=source_format,
        digest=hashlib.sha256(data).hexdigest(),
    )


def install_background(store: object, processed: ProcessedImage) -> str:
    directory = appearance_dir(store)
    filename = f"background-{processed.digest[:20]}{STORED_SUFFIX}"
    target = directory / filename
    temp = directory / f".{filename}.tmp-{os.getpid()}"
    try:
        temp.write_bytes(processed.data)
        os.replace(temp, target)
    finally:
        if temp.exists():
            temp.unlink(missing_ok=True)
    return filename


def remove_unused_backgrounds(store: object, keep: str | None) -> None:
    directory = appearance_dir(store)
    for path in directory.glob(f"background-*{STORED_SUFFIX}"):
        if keep and path.name == keep:
            continue
        try:
            path.unlink()
        except OSError:
            continue


def delete_background(store: object, settings: AppearanceSettings) -> AppearanceSettings:
    remove_unused_backgrounds(store, None)
    settings.background_file = None
    settings.background_name = ""
    # Removing a wallpaper is not a theme choice. Keep the saved theme.
    save_appearance(store, settings)
    return settings


def reset_appearance(store: object) -> AppearanceSettings:
    remove_unused_backgrounds(store, None)
    settings = default_appearance()
    save_appearance(store, settings)
    return settings


def background_path(store: object, settings: AppearanceSettings) -> Path | None:
    if not settings.background_file:
        return None
    path = appearance_dir(store) / Path(settings.background_file).name
    return path if path.is_file() else None


def background_bytes(store: object, settings: AppearanceSettings) -> bytes | None:
    path = background_path(store, settings)
    if path is None:
        return None
    try:
        if path.stat().st_size > MAX_UPLOAD_BYTES:
            return None
        return path.read_bytes()
    except OSError:
        return None


def background_data_uri(store: object, settings: AppearanceSettings) -> str | None:
    data = background_bytes(store, settings)
    if not data:
        return None
    return bytes_data_uri(data)


def bytes_data_uri(data: bytes) -> str:
    return "data:image/webp;base64," + base64.b64encode(data).decode("ascii")


def _bounded_int(value: object, default: int, low: int, high: int) -> int:
    try:
        number = int(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return default
    return max(low, min(high, number))


def _bounded_float(value: object, default: float, low: float, high: float) -> float:
    try:
        number = float(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return default
    if number != number or number in (float("inf"), float("-inf")):
        return default
    return max(low, min(high, number))
